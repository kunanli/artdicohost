#!/usr/bin/env python3
"""Build bounded OFL-derived WOFF2 subsets from the two organizer-supplied TTFs.
Requires system fontTools + Brotli. No source TTF or personal data is copied.
"""
import argparse, hashlib, json
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont


def ranges(points):
    result = []
    for cp in sorted(points):
        if result and cp == result[-1][1] + 1:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return result


def build(source, points, output, weight, identifier, license_text):
    font = TTFont(source, recalcTimestamp=False)
    opts = subset.Options()
    opts.name_IDs = ['*']
    opts.name_legacy = True
    opts.name_languages = ['*']
    opts.layout_features = ['*']
    worker = subset.Subsetter(options=opts)
    worker.populate(unicodes=points)
    worker.subset(font)
    family = 'ARTDiCO Invitation SC'
    style = 'Medium' if weight == 500 else 'Regular'
    renamed = {1: family, 2: style, 3: 'ARTDiCOInvitationSC-' + style + '-' + identifier,
               4: family + ' ' + style, 6: 'ARTDiCOInvitationSC-' + style + '-' + identifier,
               16: family, 17: style}
    for record in font['name'].names:
        if record.nameID in renamed:
            record.string = renamed[record.nameID].encode(record.getEncoding())
        elif record.nameID == 13:
            record.string = license_text.encode(record.getEncoding())
    font.flavor = 'woff2'
    font.save(output)
    result = TTFont(output)
    coverage = set(result.getBestCmap())
    if coverage != set(points):
        raise ValueError('Output cmap changed')
    data = output.read_bytes()
    if len(data) > 2 * 1024 * 1024:
        raise ValueError('A font exceeds the existing static asset limit')
    spans = ranges(coverage)
    return {'id': identifier, 'file': output.name, 'weight': weight,
            'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest(),
            'codePointCount': len(coverage), 'codePointRanges': spans,
            'unicodeRange': ','.join('U+%X' % a if a == b else 'U+%X-%X' % (a, b) for a, b in spans)}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--regular', required=True, type=Path)
    parser.add_argument('--medium', required=True, type=Path)
    parser.add_argument('--root', default=Path(__file__).resolve().parents[1], type=Path)
    args = parser.parse_args()
    root = args.root.resolve()
    license_text = (root / 'docs/licenses/invitation-fonts-OFL.txt').read_text()
    if 'SIL OPEN FONT LICENSE Version 1.1' not in license_text or 'PERMISSION & CONDITIONS' not in license_text:
        raise ValueError('The complete redistribution license must accompany each font')
    target = root / 'src/assets/fonts'
    target.mkdir(parents=True, exist_ok=True)
    medium_points = sorted(TTFont(args.medium).getBestCmap())
    parts = []
    union = set()
    for i in range(3):
        points = medium_points[len(medium_points) * i // 3:len(medium_points) * (i + 1) // 3]
        assert not union.intersection(points)
        union.update(points)
        parts.append(build(args.medium, points, target / ('invitation-medium-part%d.woff2' % (i + 1)), 500, 'medium-%d' % (i + 1), license_text))
    assert union == set(medium_points)
    available = set(TTFont(args.regular).getBestCmap())
    date_chars = '年月日时分至点零一二三四五六七八九十星期周上午下午时间地点诚邀相聚一起创意不息深圳前海号楼—–：／（）·'
    requested = set(range(0x20, 0x180)) | set(range(0x2000, 0x2070)) | set(map(ord, date_chars))
    regular = build(args.regular, sorted(available & requested), target / 'invitation-regular.woff2', 400, 'regular', license_text)
    def js_entry(item):
        minimal = {key: item[key] for key in ('id', 'unicodeRange', 'codePointRanges')}
        encoded = json.dumps(minimal, ensure_ascii=True, separators=(',', ':'))
        return encoded[:-1] + ",url:new URL('../assets/fonts/" + item['file'] + "',import.meta.url).href}"
    js = '/** Generated by scripts/prepare-invitation-fonts.py; exact cmap ranges, no source TTF. */\n'
    js += 'export const INVITATION_MEDIUM_PARTS = Object.freeze([' + ','.join(js_entry(p) for p in parts) + ']);\n'
    js += 'export const INVITATION_REGULAR_PART = Object.freeze(' + js_entry(regular) + ');\n'
    (root / 'src/lib/invitation-font-data.mjs').write_text(js)
    sources = {name: {'file': source.name, 'sha256': hashlib.sha256(source.read_bytes()).hexdigest()} for name, source in [('regular', args.regular), ('medium', args.medium)]}
    manifest = {'schemaVersion': 1, 'derivedFamily': 'ARTDiCO Invitation SC', 'license': 'SIL Open Font License 1.1', 'sources': sources, 'mediumSourceCodePoints': len(medium_points), 'parts': parts, 'regular': regular}
    (root / 'docs/invitation-font-manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'mediumCodePoints': len(medium_points), 'files': [{'file': p['file'], 'bytes': p['bytes'], 'sha256': p['sha256']} for p in parts + [regular]], 'totalBytes': sum(p['bytes'] for p in parts + [regular])}))


if __name__ == '__main__':
    main()
