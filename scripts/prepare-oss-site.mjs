import { readdir, readFile, writeFile, mkdir, lstat } from 'node:fs/promises';
import { resolve, dirname, extname, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = fileURLToPath(new URL('../', import.meta.url));
const allowedExtensions = new Set(['.html', '.css', '.js', '.mjs', '.png', '.svg', '.jpg', '.jpeg', '.webp', '.avif', '.woff', '.woff2', '.ico']);
export const MAX_FILE_BYTES = 20 * 1024 * 1024;
export const sha256 = (data) => createHash('sha256').update(data).digest('hex');

export function validatePublicPath(path) {
  if (!path || path.includes('\\') || path.startsWith('/') || path.split('/').some(part => !part || part.startsWith('.') || /[\u0000-\u001f]/u.test(part))) throw new Error('Unsafe public path');
  const namedRoute = ['index.html', '404.html', 'invitation/index.html', 'admin/index.html', 'admin/contacts/index.html', 'invitations/template-blank.png'].includes(path);
  if (!allowedExtensions.has(extname(path).toLowerCase()) || (!namedRoute && !/^_astro\/[A-Za-z0-9_.\/-]+$/.test(path))) throw new Error('Unexpected public file: ' + path);
  return path;
}

async function checkedRead(path) {
  const stat = await lstat(path);
  if (!stat.isFile() || stat.isSymbolicLink() || stat.size > MAX_FILE_BYTES) throw new Error('Public file must be a regular file of at most 20 MiB');
  return readFile(path);
}

async function checkedPublicRead(directory, path) {
  let cursor = directory;
  if ((await lstat(cursor)).isSymbolicLink()) throw new Error('Symbolic links cannot be published');
  for (const part of path.split('/')) {
    cursor = resolve(cursor, part);
    if ((await lstat(cursor)).isSymbolicLink()) throw new Error('Symbolic links cannot be published');
  }
  return checkedRead(cursor);
}

// Static routes generated by Astro can refer to shared CSS and JavaScript chunks.
// Only traverse assets reachable from the explicitly selected public pages.
export function referencedAssets(text, currentPath) {
  const assets = new Set();
  for (const match of text.matchAll(/["'`(](\/?_astro\/[^"'`\s)<>]+|\.{1,2}\/[^"'`\s)<>]+\.(?:m?js|css|woff2?|png|svg|webp))(?:["'`)])/g)) {
    const value = match[1].split(/[?#]/)[0];
    const target = value.startsWith('/') ? value.slice(1) : value.startsWith('_astro/') ? value : posix.normalize(posix.join(posix.dirname(currentPath), value));
    if (!target.startsWith('_astro/')) throw new Error('Unexpected generated asset reference');
    assets.add(validatePublicPath(target));
  }
  return [...assets];
}

export function statusPage(title, message) {
  return '<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex,nofollow"><title>' + title + '｜ARTDiCO HOST</title><style>body{font:18px/1.7 system-ui,sans-serif;color:#13213d;background:#f5f7fc;margin:0}main{max-width:680px;margin:12vh auto;padding:32px}a{color:#1448ef}h1{line-height:1.3}</style><main><p>ARTDiCO HOST / 2026</p><h1>' + title + '</h1><p>' + message + '</p><a href="/">返回活动首页</a></main></html>';
}

export async function prepareOssSite({ distDirectory = resolve(root, 'dist'), outputDirectory = resolve(root, '.local-data/oss-publish'), commit = process.env.GITHUB_SHA } = {}) {
  if (!/^[a-f0-9]{40}$/.test(commit ?? '')) throw new Error('An exact source commit is required');
  // Refuse a populated destination; never recursively delete a computed path.
  await mkdir(outputDirectory, { recursive: true });
  if ((await readdir(outputDirectory)).length) throw new Error('Publication directory must be empty');
  const selected = new Map();
  const pending = ['index.html', 'invitation/index.html'];
  while (pending.length) {
    const path = validatePublicPath(pending.pop());
    if (selected.has(path)) continue;
    const data = await checkedPublicRead(distDirectory, path);
    selected.set(path, data);
    if (/\.(?:html|css|m?js)$/.test(path)) {
      const text = data.toString('utf8');
      if (/-----BEGIN [A-Z ]*PRIVATE KEY-----|github_pat_[A-Za-z0-9_]{30,}|ghp_[A-Za-z0-9]{30,}/.test(text)) throw new Error('Possible secret in public build');
      pending.push(...referencedAssets(text, path));
    }
  }
  selected.set('invitations/template-blank.png', await checkedPublicRead(distDirectory, 'invitations/template-blank.png'));
  selected.set('404.html', Buffer.from(statusPage('找不到这个页面', '页面可能已移动。你可以返回活动首页查看最新安排。')));
  const notice = Buffer.from(statusPage('云端工作人员后台尚未开放', '当前网站为静态预览。联系人、场次管理、Apple Wallet 和邮件功能仍在接入中；此处不收集账号或报名资料。'));
  selected.set('admin/index.html', notice);
  selected.set('admin/contacts/index.html', notice);
  const files = [];
  for (const [path, data] of [...selected].sort(([a], [b]) => a.localeCompare(b))) {
    await mkdir(dirname(resolve(outputDirectory, path)), { recursive: true });
    await writeFile(resolve(outputDirectory, path), data);
    files.push({ path, bytes: data.length, sha256: sha256(data) });
  }
  const manifest = { schemaVersion: 1, commit, bucket: 'artdicohost-web-hk', region: 'cn-hongkong', files };
  await writeFile(resolve(outputDirectory, 'publication-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  return manifest;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const manifest = await prepareOssSite({ outputDirectory: process.argv[2] ? resolve(process.argv[2]) : undefined });
  console.log('Prepared ' + manifest.files.length + ' public files for commit ' + manifest.commit + '.');
}
